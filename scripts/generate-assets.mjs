#!/usr/bin/env node
/**
 * Generates `src/assets/bundle.ts` from the standalone CSS/JS files in `src/assets/`.
 *
 * Keeps `src/assets/*.css` and `src/assets/*.js` as real, lintable source files while
 * letting `src/routes/assets.ts` and `src/routes/shell.ts` import their bytes via plain
 * standard TypeScript — portable across Cloudflare Workers (`wrangler`), Node, Vitest,
 * and Deno without runtime filesystem reads or `with { type: "text" }` assertions.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const assetsDir = join(here, "..", "src", "assets");
const outFile = join(assetsDir, "bundle.ts");

const ASSET_FILES = [
  "listen.css",
  "listen.js",
  "listen-landing.css",
  "listen-landing.js",
  "admin.css",
  "admin.js",
  "same-origin-path.js",
  "confirm-shared.js",
  "home.css",
  "home.js",
  "cwv-stats.js",
  "cwv.js",
  "tooltip-client.js",
];

const entries = ASSET_FILES.map((name) => {
  const content = readFileSync(join(assetsDir, name), "utf8");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(content)},`;
});

const output = `// AUTO-GENERATED by scripts/generate-assets.mjs — do not edit by hand.
// Edit the source files under src/assets/*.{css,js} and re-run \`npm run build:assets\`.

export const ASSETS_RAW = {
${entries.join("\n")}
} as const;

export type RawAssetName = keyof typeof ASSETS_RAW;
`;

let existing = null;
try {
  existing = readFileSync(outFile, "utf8");
} catch {
  // file does not exist yet
}
if (existing !== output) {
  writeFileSync(outFile, output, "utf8");
  console.log(`[build:assets] wrote ${ASSET_FILES.length} assets to src/assets/bundle.ts`);
} else {
  console.log(`[build:assets] src/assets/bundle.ts already up to date (${ASSET_FILES.length} assets)`);
}
